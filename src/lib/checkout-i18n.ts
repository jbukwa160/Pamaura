export type CheckoutLocale = keyof typeof CHECKOUT_TEXT;
export type CheckoutTexts = { [K in keyof (typeof CHECKOUT_TEXT)["bg"]]: string };

export function checkoutTexts(locale: string): CheckoutTexts {
  return (CHECKOUT_TEXT as Record<string, CheckoutTexts>)[locale] ?? CHECKOUT_TEXT.bg;
}

export function fill(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{\{(\w+)\}\}/g, (_m, k) => String(vars[k] ?? ""));
}
